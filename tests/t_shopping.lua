-- Shift-click a row: search its materials at the auction house.

local function world(opts)
  InstallAuctionator(opts)
  AddProfession("Tailoring", 197, 1)
  Item(2589, "Linen Cloth")
  Item(2996, "Bolt of Linen Cloth")
  Item(2320, "Coarse Thread")
  Item(4238, "Linen Bag")
  Item(5000, "Spool")
  AddRecipe(197, { id = 2963, name = "Bolt of Linen Cloth", out = 2996, mats = { { 2589, 2 } } })
  AddRecipe(197, { id = 3755, name = "Linen Bag", out = 4238, mats = { { 2996, 3 }, { 2320, 3 } } })
  AddRecipe(197, { id = 3756, name = "Thread Ball", out = 5000, mats = { { 2320, 4 } } })
  local ns = Boot()
  SetPrice(2589, 50); SetPrice(2996, 150); SetPrice(2320, 30); SetPrice(4238, 1200); SetPrice(5000, 500)
  OpenProfession("Tailoring", 197)
  Slash()
  return ns
end

local function row(name)
  for _, r in ipairs(Window().rows) do if r.name == name then return r.row end end
  error("no row " .. name)
end

test("the footer explains click and shift-click", function()
  world()
  eq(NS.UI.Main.hint:GetText(), "Click: open recipe  ·  Shift-click: search materials at the AH")
  eq(ColorOf(NS.UI.Main.hint), "muted")
end)

test("shift-click with the AH open searches every material, vendor ones too", function()
  world()
  OpenAuctionHouse()
  ShiftClick(row("Linen Bag"))
  eq(LastSearch(), "advanced: Bolt of Linen Cloth x3, Coarse Thread x3")
  eq(Mock.openedRecipe, nil, "doesn't open the recipe")
end)

test("plain click still opens the recipe and doesn't search", function()
  world()
  OpenAuctionHouse()
  Click(row("Linen Bag"))
  eq(Mock.openedRecipe, 3755)
  eq(#Mock.auc.searches, 0)
end)

test("shift-click with the AH closed queues the search for the next visit", function()
  world()
  ShiftClick(row("Linen Bag").nameHit)
  eq(#Mock.auc.searches, 0)
  ok(Printed("Craft Margin: open the auction house to search for Linen Bag materials."))
  eq(NS.UI.Main.hint:GetText(), "Searching for Linen Bag materials when you open the AH")
  eq(ColorOf(NS.UI.Main.hint), "warn")
  OpenAuctionHouse()
  eq(LastSearch(), "advanced: Bolt of Linen Cloth x3, Coarse Thread x3")
  Advance(1)
  eq(ColorOf(NS.UI.Main.hint), "muted", "back to the normal hint")
  CloseAuctionHouse()
  OpenAuctionHouse()
  eq(#Mock.auc.searches, 1, "runs once")
end)

test("a newer shift-click replaces the queued search", function()
  world()
  ShiftClick(row("Linen Bag"))
  ShiftClick(row("Bolt of Linen Cloth"))
  OpenAuctionHouse()
  eq(#Mock.auc.searches, 1)
  eq(LastSearch(), "advanced: Linen Cloth x2")
end)

test("a queued search expires after 10 minutes", function()
  world()
  ShiftClick(row("Linen Bag"))
  Advance(601)
  OpenAuctionHouse()
  eq(#Mock.auc.searches, 0)
end)

test("a recipe with only vendor materials is searched too", function()
  world()
  OpenAuctionHouse()
  ShiftClick(row("Thread Ball"))
  eq(LastSearch(), "advanced: Coarse Thread x4")
end)

test("older Auctionator: exact names without quantities", function()
  world({ noAdvanced = true })
  OpenAuctionHouse()
  ShiftClick(row("Linen Bag"))
  eq(LastSearch(), "exact: Bolt of Linen Cloth, Coarse Thread")
end)

test("material names not loaded yet: searches once they arrive", function()
  world()
  OpenAuctionHouse()
  Mock.items[2996] = nil
  Mock.shift = true
  Click(row("Linen Bag"))
  Mock.shift = false
  eq(#Mock.auc.searches, 0)
  Item(2996, "Bolt of Linen Cloth")
  Advance(1)
  eq(LastSearch(), "advanced: Bolt of Linen Cloth x3, Coarse Thread x3")
end)

test("pure: search terms", function()
  local S = Boot().Shopping
  local r = { mats = { { id = 1, n = 2, src = "ah" }, { id = 2, n = 1, src = "vendor" }, { id = 3, n = 5 } } }
  local terms = S.Terms(r, function(id) return "Item" .. id end)
  eq(#terms, 3)
  eq(terms[1].searchString, "Item1")
  eq(terms[1].quantity, 2)
  eq(terms[1].isExact, true)
  eq(terms[2].searchString, "Item2", "vendor items included")
  eq(terms[3].searchString, "Item3", "no price yet: still searched")
  local none, unloaded = S.Terms(r, function(id) if id ~= 3 then return "x" end end)
  eq(none, nil)
  eq(unloaded[1], 3)
end)
