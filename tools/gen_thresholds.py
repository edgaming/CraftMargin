"""Generate Domain/ThresholdData.lua from the WoW Forever client's SkillLineAbility table.

Usage: python3 tools/gen_thresholds.py <SkillLineAbility.csv> <build> > Domain/ThresholdData.lua

Download the CSV from https://wago.tools/db2/SkillLineAbility/csv?build=<build> (WoW Forever build).
Keeps crafting recipes (a grey threshold above zero) and writes { yellow, grey } per recipe spell ID.
Green is halfway between them; orange (the required skill) isn't in this table.
"""
import csv
import sys

# Crafting skill lines: Alchemy, Blacksmithing, Cooking, Enchanting, Engineering, First Aid,
# Leatherworking, Tailoring, Mining (smelting).
SKILL_LINES = {171, 164, 185, 333, 202, 129, 165, 197, 186}


def main(path, build):
    out = {}
    with open(path, newline="", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            if int(row["SkillLine"]) not in SKILL_LINES:
                continue
            spell = int(row["Spell"])
            yellow = int(row["TrivialSkillLineRankLow"])
            grey = int(row["TrivialSkillLineRankHigh"])
            if grey <= 0 or yellow <= 0 or yellow > grey:
                continue
            out[spell] = (yellow, grey)
    print(f"-- Generated by tools/gen_thresholds.py from WoW Forever client data (SkillLineAbility, build {build}),")
    print("-- via wago.tools. { yellow, grey } skill thresholds per recipe spell ID. Do not edit by hand.")
    print("local _, ns = ...")
    print("ns.ThresholdData = {")
    for spell in sorted(out):
        y, g = out[spell]
        print(f"  [{spell}] = {{ {y}, {g} }},")
    print("}")
    print(f"-- {len(out)} recipes", file=sys.stderr)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
