"""Generate Domain/NodeData.lua: herb and mining node names -> the item they're gathered for.

Usage: python3 tools/gen_nodes.py <ClassicDB_*.sql.gz> > Domain/NodeData.lua

From the CMaNGOS Classic database: chest-type game objects (type 3) whose likely loot (an
equal-chance group, or >= 50%) is a Trade Goods item, and which are herbs (the node is named after
its item) or mineral nodes (Vein / Deposit). Names like "Rich Thorium Vein" map to Thorium Ore.
New Forever nodes aren't in it; the addon falls back to an item with the node's own name.
"""
import gzip
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_vendor_prices import split_rows

WANTED = {"gameobject_template", "gameobject_loot_template", "item_template"}


def main(path):
    cols, data, cur = {}, {t: [] for t in WANTED}, None
    with gzip.open(path, "rt", encoding="utf-8", errors="replace") as f:
        for line in f:
            m = re.match(r"CREATE TABLE `(\w+)`", line)
            if m:
                cur = m.group(1) if m.group(1) in WANTED else None
                if cur:
                    cols[cur] = []
                continue
            if cur and line.startswith("  `"):
                cols[cur].append(line.split("`")[1])
                continue
            m = re.match(r"INSERT INTO `(\w+)` VALUES (.*);\s*$", line)
            if m and m.group(1) in WANTED:
                data[m.group(1)].extend(split_rows(m.group(2)))

    def table(name):
        idx = {c: i for i, c in enumerate(cols[name])}
        return [{c: r[i] for c, i in idx.items()} for r in data[name]]

    kind = {}
    for r in table("item_template"):
        if int(r["class"]) == 7:
            kind[int(r["entry"])] = (r["name"], int(r["subclass"]))
    loot = {}
    for r in table("gameobject_loot_template"):
        item, chance = int(r["item"]), float(r["ChanceOrQuestChance"])
        if item in kind and (chance == 0 or chance >= 50):
            loot.setdefault(int(r["entry"]), []).append(item)
    byName = {}
    for item, (name, sub) in kind.items():
        if sub == 9:  # herb
            byName.setdefault(name, item)
    nodes = {}
    for r in table("gameobject_template"):
        if int(r["type"]) != 3:
            continue
        if r["name"] in byName:  # herb nodes are named after their herb
            nodes.setdefault(r["name"], byName[r["name"]])
            continue
        items = loot.get(int(r["data1"]))
        if not items:
            continue
        name = r["name"]
        named = next((i for i in items if kind[i][0] in name), None)
        mineral = re.search(r"\b(Vein|Deposit)\b", name)
        if named and not mineral:
            nodes.setdefault(name, named)
        elif mineral:
            ore = next((i for i in items if kind[i][0].endswith("Ore")), None)
            if ore:
                nodes.setdefault(name, ore)

    print("-- Generated by tools/gen_nodes.py from the CMaNGOS Classic database.")
    print("-- Herb and mining node name -> item ID gathered from it. Do not edit by hand.")
    print("local _, ns = ...")
    print("ns.NodeData = {")
    for name in sorted(nodes):
        esc = name.replace("\\", "\\\\").replace('"', '\\"')
        print(f'  ["{esc}"] = {nodes[name]}, -- {kind[nodes[name]][0]}')
    print("}")
    print(f"-- {len(nodes)} nodes", file=sys.stderr)


if __name__ == "__main__":
    main(sys.argv[1])
