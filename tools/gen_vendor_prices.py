"""Generate Domain/VendorData.lua from the CMaNGOS Classic world database.

Usage: python3 tools/gen_vendor_prices.py <ClassicDB_*.sql.gz> > Domain/VendorData.lua

Keeps items that:
  * are Consumable (0), Reagent (5) or Trade Goods (7) class,
  * are sold in unlimited supply by at least one vendor (npc_vendor or npc_vendor_template),
  * have a buy price.

Price per single item = BuyPrice / BuyCount, rounded up to whole copper.
In Classic the base vendor price is the same at every vendor; only reputation
discounts change it, and those are picked up in game when you visit a vendor.
"""
import gzip
import math
import re
import sys

WANTED = {"item_template", "npc_vendor", "npc_vendor_template"}


def split_rows(values):
    """Parse the VALUES part of an INSERT into a list of tuples of strings."""
    rows, row, field, i, n = [], [], [], 0, len(values)
    in_str = False
    depth = 0
    while i < n:
        c = values[i]
        if in_str:
            if c == "\\":
                field.append(values[i + 1])
                i += 2
                continue
            if c == "'":
                in_str = False
            else:
                field.append(c)
        elif c == "'":
            in_str = True
        elif c == "(":
            depth += 1
            row, field = [], []
        elif c == ")":
            depth -= 1
            row.append("".join(field))
            rows.append(row)
        elif c == "," and depth == 1:
            row.append("".join(field))
            field = []
        elif depth == 1:
            field.append(c)
        i += 1
    return rows


def main(path):
    cols, data, current = {}, {t: [] for t in WANTED}, None
    with gzip.open(path, "rt", encoding="utf-8", errors="replace") as f:
        for line in f:
            m = re.match(r"CREATE TABLE `(\w+)`", line)
            if m:
                current = m.group(1) if m.group(1) in WANTED else None
                if current:
                    cols[current] = []
                continue
            if current and line.startswith("  `"):
                cols[current].append(line.split("`")[1])
                continue
            m = re.match(r"INSERT INTO `(\w+)` VALUES (.*);\s*$", line)
            if m and m.group(1) in WANTED:
                data[m.group(1)].extend(split_rows(m.group(2)))

    def table(name):
        idx = {c: i for i, c in enumerate(cols[name])}
        return [{c: r[i] for c, i in idx.items()} for r in data[name]]

    sold = set()
    for t in ("npc_vendor", "npc_vendor_template"):
        for r in table(t):
            if int(r["maxcount"]) == 0:
                sold.add(int(r["item"]))

    out = []
    for r in table("item_template"):
        item = int(r["entry"])
        if item not in sold or int(r["class"]) not in (0, 5, 7):
            continue
        price, count = int(r["BuyPrice"]), max(1, int(r["BuyCount"]))
        if price <= 0:
            continue
        out.append((item, math.ceil(price / count), r["name"]))
    out.sort()

    print("-- Generated by tools/gen_vendor_prices.py from the CMaNGOS Classic database.")
    print("-- Base vendor price in copper for one item. Do not edit by hand.")
    print("local _, ns = ...")
    print("-- (generated table, read by Domain/Vendor.lua)")
    print("ns.VendorData = {")
    for item, price, name in out:
        print(f"  [{item}] = {price}, -- {name}")
    print("}")
    print(f"-- {len(out)} items", file=sys.stderr)


if __name__ == "__main__":
    main(sys.argv[1])
